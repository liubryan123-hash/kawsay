// DOM integration checks. Requires the existing jsdom development dependency.
import { JSDOM } from 'jsdom';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
const html=readFileSync(new URL('../demo/kawsay-simulador.html',import.meta.url),'utf8');
const code=html.match(/<script type="module">([\s\S]*)<\/script>/)[1];
const dom=new JSDOM(html.replace(/<script[\s\S]*?<\/script>/,''),{url:'http://localhost:4173',runScripts:'outside-only'});
const w=dom.window;
Object.defineProperty(w.crypto,'randomUUID',{value:randomUUID});
w.eval(code);
const $=s=>{const el=w.document.querySelector(s);assert.ok(el,'Missing element '+s);return el;};
const click=s=>$(s).click();
const change=(s,v)=>{const el=$(s);el.value=v;el.dispatchEvent(new w.Event('change',{bubbles:true}));};
const text=()=>$('#app').textContent;
assert.ok(text().includes('Tripulación · día 20'));
assert.equal(w.document.querySelectorAll('.crew-card').length,4);
click('[data-action="mission-detail"][data-crew="A"]');
assert.equal(w.document.querySelectorAll('svg').length,4);
assert.match(text(),/NEWS2 [78]/);
click('[data-tab="packet"]');
assert.ok(text().includes('Earth Packet · Tripulante A'));
assert.ok(text().includes('8'));
click('[data-tab="registro"]');
assert.ok($('[name="newsAlert"]'));
$('[name="hr"]').value='81';
$('[name="note"]').value='Borrador exclusivo A';
change('#active-crew','B');
assert.equal($('[name="hr"]').value,'');
assert.equal($('[name="note"]').value,'');
$('[name="hr"]').value='62';
change('#form-crew','A');
assert.equal($('[name="hr"]').value,'81');
assert.equal($('[name="note"]').value,'Borrador exclusivo A');
change('#form-crew','B');
assert.equal($('[name="hr"]').value,'62');
change('#active-crew','A');
assert.equal($('[name="hr"]').value,'81');
$('[name="spo2"]').value='97%';
$('[name="note"]').value='<img src=x onerror="alert(1)"> reporte ficticio';
$('#entry-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
assert.ok(text().includes('Confirma tu registro'));
assert.equal(w.document.querySelectorAll('img').length,0);
click('[data-action="confirm"]');
assert.ok(text().includes('Registro guardado'));
click('[data-tab="medico"]');
assert.ok(text().includes('1 registros'));
$('textarea[name="review"]').value='Revisión de prueba';
$('.review-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
assert.ok(text().includes('Revisión registrada'));
click('[data-tab="visor"]');
assert.ok(text().includes('97'));
click('[data-action="help"]');
click('[data-tab="medico"]');
click('[data-action="ack"][data-role="medical"]');
assert.equal($('[data-action="close-alert"]').disabled,true);
change('#active-crew','B');
click('[data-tab="apoyo"]');
click('[data-action="ack"][data-role="buddy"]');
click('[data-tab="medico"]');
assert.equal($('[data-action="close-alert"]').disabled,false);
click('[data-action="close-alert"]');
assert.ok(text().includes('Simulacro cerrado'));
change('#active-crew','A');
click('[data-tab="packet"]');
change('#packet-mode','local');
assert.ok(text().includes('1 solicitudes de apoyo'));
assert.ok(text().includes('4 acciones registradas'));
const persisted=JSON.parse(w.localStorage.getItem('kawsay.simulador.v1'));
assert.equal(persisted.records.length,1);assert.equal(persisted.reviews.length,1);
assert.ok(persisted.alerts[0].closedAt);
console.log('DOM smoke passed: mission → graphs → packet → manual entry → review → visor → support confirmations → local packet.');
dom.window.close();
